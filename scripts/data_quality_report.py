"""Write docs/data_quality_report.md and data-quality metrics from the built DuckDB + dbt results.

Run after `dbt build` (reads dbt/zoneshift/target/run_results.json for test counts).
Every number in the report is queried here; nothing is typed by hand.

Usage:
    python scripts/data_quality_report.py
"""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import duckdb

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "ingestion"))
from utils import DB_PATH, METRICS_PATH, ROOT, update_metrics  # noqa: E402

RUN_RESULTS = ROOT / "dbt" / "zoneshift" / "target" / "run_results.json"
REPORT_PATH = ROOT / "docs" / "data_quality_report.md"

FLAGS = {
    "flag_nonpositive_distance": "Non-positive (or missing) trip distance",
    "flag_negative_fare": "Negative metered fare",
    "flag_dropoff_before_pickup": "Dropoff before pickup",
    "flag_over_3_hours": "Trip longer than 3 hours",
    "flag_over_80_mph": "Implied speed over 80 mph (incl. zero duration with distance)",
    "flag_outside_window": "Pickup outside 2024-01-01 to 2025-12-31",
    "flag_unknown_zone": "Pickup or dropoff zone unknown (264/265)",
}


def dbt_test_summary() -> dict:
    if not RUN_RESULTS.exists():
        raise SystemExit(f"{RUN_RESULTS} not found: run `make dbt` first")
    rr = json.loads(RUN_RESULTS.read_text())
    tests = [r for r in rr["results"] if r["unique_id"].startswith("test.")]
    status = lambda s: sum(1 for t in tests if t["status"] == s)  # noqa: E731
    warned = sorted(
        (t["unique_id"].split(".")[2], t.get("failures")) for t in tests if t["status"] == "warn"
    )
    return {
        "total": len(tests),
        "pass": status("pass"),
        "warn": status("warn"),
        "fail": status("fail") + status("error"),
        "warned": warned,
        "generated_at": rr["metadata"]["generated_at"],
        "command": " ".join(rr["args"].get("invocation_command", "dbt build").split()[:2]),
    }


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.2f}%" if b else "n/a"


def main() -> None:
    con = duckdb.connect(str(DB_PATH), read_only=True)
    q = lambda sql: con.execute(sql).fetchall()  # noqa: E731

    flag_cols = ", ".join(f"count(*) filter (where {f})" for f in FLAGS)
    only_cols = ", ".join(
        f"count(*) filter (where {f} and not ({' or '.join(g for g in FLAGS if g != f)}))" for f in FLAGS
    )
    by_service = q(f"""
        select coalesce(service_type, 'all') as service_type, count(*),
               count(*) filter (where is_excluded), {flag_cols}, {only_cols}
        from intermediate.int_trips_cleaned
        group by rollup (service_type)
        order by service_type = 'all', service_type desc
    """)
    rows = {r[0]: r for r in by_service}
    total = rows["all"]
    n_in, n_excl = total[1], total[2]
    n_kept = n_in - n_excl
    flag_any = dict(zip(FLAGS, total[3:3 + len(FLAGS)]))
    flag_only = dict(zip(FLAGS, total[3 + len(FLAGS):]))

    fct_rows = q("select count(*) from marts.fct_trips")[0][0]
    raw_total = json.loads(METRICS_PATH.read_text()).get("raw_rows_trips_total")

    fee_pre, fee_pre_min, fee_pre_max, fee_pre_ends_after = q("""
        select count(*), min(pickup_at), max(pickup_at),
               count(*) filter (where dropoff_at >= timestamp '2025-01-05')
        from marts.fct_trips
        where pickup_at < timestamp '2025-01-05' and coalesce(cbd_congestion_fee, 0) <> 0
    """)[0]
    fee_post_total, fee_post_nonnull = q("""
        select count(*), count(cbd_congestion_fee) from marts.fct_trips
        where pickup_at >= timestamp '2025-01-05'
    """)[0]
    fee_dist = q("""
        select cbd_congestion_fee, count(*) from marts.fct_trips
        where pickup_at >= timestamp '2025-01-05'
        group by 1 order by 2 desc
    """)
    fee_anomalies = sum(n for v, n in fee_dist if v is not None and v not in (0, 0.75))

    zones = q("""
        select count(*) filter (where is_cbd), count(*) filter (where is_border_zone),
               string_agg(zone, ', ' order by location_id) filter (where is_border_zone)
        from marts.dim_zone
    """)[0]
    agg_rows = q("select count(*) from marts.agg_zone_day")[0][0]
    tests = dbt_test_summary()

    # ---------- report ----------
    lines = [
        "# Data quality report",
        "",
        f"_Generated by `scripts/data_quality_report.py` at "
        f"{datetime.now(timezone.utc).isoformat(timespec='seconds')} from `data/zoneshift.duckdb` "
        f"and dbt run results ({tests['generated_at'][:19]}Z). Do not edit by hand._",
        "",
        "Source: NYC TLC yellow and green trip records, monthly files 2024-01 to 2025-12. "
        "Trip records are submitted by technology vendors and are not verified by TLC.",
        "",
        "## Rows in and retained",
        "",
        "| Service | Rows in | Excluded | Retained | % retained |",
        "|---|---:|---:|---:|---:|",
    ]
    for svc in ["yellow", "green", "all"]:
        r = rows[svc]
        lines.append(f"| {svc} | {r[1]:,} | {r[2]:,} | {r[1] - r[2]:,} | {pct(r[1] - r[2], r[1])} |")
    lines += [
        "",
        f"Rows in matches raw ingestion total: **{n_in == raw_total}** ({n_in:,} vs {raw_total:,}). "
        f"`fct_trips` rows: {fct_rows:,} (equals retained: **{fct_rows == n_kept}**).",
        "",
        "## Rows excluded by each flag",
        "",
        "Flags overlap, so a trip can fail several rules. \"Flagged\" counts every trip failing the rule; "
        "\"Only this flag\" counts trips excluded by that rule alone.",
        "",
        "| Rule | Flagged | % of rows in | Only this flag |",
        "|---|---:|---:|---:|",
    ]
    for f, label in FLAGS.items():
        lines.append(f"| {label} (`{f}`) | {flag_any[f]:,} | {pct(flag_any[f], n_in)} | {flag_only[f]:,} |")
    lines += [
        f"| **Any flag (`is_excluded`)** | **{n_excl:,}** | **{pct(n_excl, n_in)}** | |",
        "",
        "## CBD congestion fee checks (clean set)",
        "",
        f"- Trips picked up before 2025-01-05 with a non-zero `cbd_congestion_fee`: **{fee_pre:,}** "
        f"(pickups from {fee_pre_min} to {fee_pre_max}; {fee_pre_ends_after:,} of them end on or after "
        "2025-01-05 00:00). Trips spanning midnight into the policy start can legitimately be charged, "
        "so these are kept in the clean set and surfaced by a warn-level dbt test.",
        f"- Post-policy clean trips: {fee_post_total:,}; with a non-null fee: {fee_post_nonnull:,}.",
        f"- Post-policy fees other than $0 / $0.75 / null: **{fee_anomalies:,}** "
        f"({pct(fee_anomalies, fee_post_total)} of post-policy trips; hard-fail threshold 0.1%).",
        "",
        "| Fee value (USD) | Post-policy clean trips |",
        "|---:|---:|",
    ]
    for v, n in fee_dist:
        lines.append(f"| {'null' if v is None else f'{v:.2f}'} | {n:,} |")
    lines += [
        "",
        "## Zones",
        "",
        f"- CBD (treated) zones from the MTA list: **{zones[0]}**.",
        f"- Border zones (non-CBD Manhattan zones within 100 ft of a CBD polygon): **{zones[1]}**: {zones[2]}.",
        f"- `agg_zone_day` rows (zone x day x service incl. 'all'): {agg_rows:,}.",
        "",
        "## dbt tests",
        "",
        f"From the latest `{tests['command']}`: **{tests['total']}** tests, "
        f"{tests['pass']} pass, {tests['warn']} warn, {tests['fail']} fail/error.",
        "",
    ]
    if tests["warned"]:
        lines += ["Warnings (by design, data issues surfaced rather than blocking):", ""]
        lines += [f"- `{name}`: {n:,} rows" for name, n in tests["warned"]]
        lines.append("")
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines))

    update_metrics({
        "dq_rows_in": n_in,
        "dq_rows_excluded": n_excl,
        "dq_rows_retained": n_kept,
        "dq_pct_retained": round(100 * n_kept / n_in, 2),
        "dq_rows_retained_yellow": rows["yellow"][1] - rows["yellow"][2],
        "dq_rows_retained_green": rows["green"][1] - rows["green"][2],
        "dq_flagged_by_rule": flag_any,
        "dq_cbd_fee_nonzero_pre_policy": fee_pre,
        "dq_cbd_fee_anomalies_post_policy": fee_anomalies,
        "fct_trips_rows": fct_rows,
        "agg_zone_day_rows": agg_rows,
        "cbd_zone_count": zones[0],
        "border_zone_count": zones[1],
        "dbt_tests_total": tests["total"],
        "dbt_tests_pass": tests["pass"],
        "dbt_tests_warn": tests["warn"],
        "dbt_tests_fail": tests["fail"],
    })
    print(f"Wrote {REPORT_PATH.relative_to(ROOT)}: {n_in:,} in, {n_kept:,} retained ({pct(n_kept, n_in)}); "
          f"dbt tests {tests['pass']}/{tests['total']} pass, {tests['warn']} warn, {tests['fail']} fail")


if __name__ == "__main__":
    main()
