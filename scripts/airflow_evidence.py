"""Write docs/airflow_run.md: task states and key log lines for zoneshift_monthly runs.

Task and run states come from the Airflow CLI (the running docker compose stack); key lines come
from the task logs under orchestration/airflow/logs/ (JSON lines).

Usage:
    python scripts/airflow_evidence.py <run_id> [<run_id> ...]
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOGS = ROOT / "orchestration" / "airflow" / "logs" / "dag_id=zoneshift_monthly"
OUT = ROOT / "docs" / "airflow_run.md"
TASKS = ["detect_months", "download", "validate", "load_duckdb", "dbt_build",
         "data_quality_report", "refresh_dashboard_exports"]
KEEP = re.compile(r"Latest loaded|Returned value|Done|Validated|window|Wrote|Exported|exited with "
                  r"return code|Nothing new|Task failed|skipped_existing|downloaded ")
ANSI = re.compile(r"\x1b\[[0-9;]*m")
COMPOSE_DIR = ROOT / "orchestration" / "airflow"


def airflow_json(*args: str) -> list[dict]:
    out = subprocess.run(
        ["docker", "compose", "exec", "-T", "airflow-scheduler", "airflow", *args, "-o", "json"],
        cwd=COMPOSE_DIR, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def task_lines(run_dir: Path, task: str) -> tuple[list[str], int]:
    attempts = sorted((run_dir / f"task_id={task}").glob("attempt=*.log"))
    if not attempts:
        return [], 0
    events = []
    for line in attempts[-1].read_text().splitlines():
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    lines = [ANSI.sub("", e.get("event", "")) for e in events]
    kept = [ln for ln in lines if KEEP.search(ln) and not ln.startswith("::")][-6:]
    return kept, len(attempts)


def main() -> None:
    runs = sys.argv[1:]
    if not runs:
        raise SystemExit(__doc__)
    out = [
        "# Airflow run evidence: `zoneshift_monthly`",
        "",
        "_Generated by `scripts/airflow_evidence.py` from the task logs in "
        "`orchestration/airflow/logs/` (Airflow 3.3.2, LocalExecutor, Docker)._",
        "",
    ]
    run_states = {r["run_id"]: r for r in airflow_json("dags", "list-runs", "zoneshift_monthly")}
    for run in runs:
        run_dir = LOGS / f"run_id={run}"
        r = run_states[run]
        states = {t["task_id"]: t for t in airflow_json("tasks", "states-for-dag-run",
                                                         "zoneshift_monthly", run)}
        out += [f"## Run `{run}`: **{r['state']}**", "",
                f"Started {r.get('start_date')}, ended {r.get('end_date')}.", "",
                "| Task | State | Attempts | Start | End |", "|---|---|---:|---|---|"]
        details = []
        for t in TASKS:
            kept, n = task_lines(run_dir, t)
            st = states.get(t, {})
            out.append(f"| `{t}` | {st.get('state')} | {n} | {(st.get('start_date') or '')[:19]} "
                       f"| {(st.get('end_date') or '')[:19]} |")
            if kept:
                details += [f"**{t}**", "", "```", *kept, "```", ""]
        out += ["", *details]
    OUT.write_text("\n".join(out))
    print(f"Wrote {OUT.relative_to(ROOT)} for {len(runs)} run(s)")


if __name__ == "__main__":
    main()
