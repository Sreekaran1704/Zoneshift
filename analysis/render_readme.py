"""Render the README's generated blocks from results/metrics.json (no hand-typed numbers).

Replaces everything between <!-- RESULTS:START --> / <!-- RESULTS:END --> (causal analysis) and
<!-- KEYNUMBERS:START --> / <!-- KEYNUMBERS:END --> (pipeline, quality, warehouses, agent).

Usage:
    python analysis/render_readme.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
METRICS = ROOT / "results" / "metrics.json"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"

LABELS = {
    "log_trips": "Trip volume, ln(1 + trips)",
    "median_fare": "Median metered fare (USD)",
    "avg_speed_mph": "Average speed (mph)",
    "card_tip_pct": "Card tip (% of fare)",
}
ROBUST_LABELS = {
    "placebo_2024-07-01": "Placebo cutoff 2024-07-01 (2024 only)",
    "include_border_zones": "Include border zones in control",
    "yellow_only": "Yellow taxis only",
    "drop_holiday_weeks": "Drop holiday weeks",
    "exploratory_spillover_border_vs_control": "Exploratory: border zones vs control",
}
ALPHA = 0.05


def fmt_p(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def render(m: dict) -> str:
    # metrics.json sorts keys; restore the pre-registered outcome order
    main = {o: m["did_main"][o] for o in LABELS}
    rob = {spec: {o: r[o] for o in LABELS} for spec, r in m["did_robustness"].items()}
    s = m["analysis_sample"]
    desc = m["descriptive_pre_post_by_zone_group"]
    pretrend_fail = [o for o, r in main.items() if r["pretrend_wald_p"] < ALPHA]
    placebo_sig = [o for o, r in rob["placebo_2024-07-01"].items() if r["p_value"] < ALPHA]
    spill = rob["exploratory_spillover_border_vs_control"]["log_trips"]

    lines = [
        START,
        "_This block is generated by `analysis/render_readme.py` from `results/metrics.json`._",
        "",
        f"**Sample:** {s['zones_treated']} CBD zones vs {s['zones_control']} control zones over "
        f"{s['days']} days; {s['zones_dropped_activity_rule_noncbd']} rarely served non-CBD zones and "
        f"{s['zones_dropped_activity_rule_cbd']} CBD zones dropped by the pre-registered activity rule.",
        "",
        "### Main difference-in-differences (pre-registered)",
        "",
        "| Outcome | Estimate | 95% CI | p | p (Holm) | Pre-trend test p | N zone-days |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for o, r in main.items():
        est = f"{r['coef']:.3f}"
        if r.get("pct_change") is not None:
            est += f" ({r['pct_change']:+.1f}%)"
        lines.append(f"| {LABELS[o]} | {est} | [{r['ci_low']:.3f}, {r['ci_high']:.3f}] | "
                     f"{fmt_p(r['p_value'])} | {fmt_p(r['p_holm'])} | {fmt_p(r['pretrend_wald_p'])} "
                     f"| {r['n_obs']:,} |")

    lines += ["", "### Robustness checks (pre-registered) and exploratory comparison", "",
              "| Specification | " + " | ".join(LABELS[o] for o in main) + " |",
              "|---|" + "---:|" * len(main)]
    for spec, label in ROBUST_LABELS.items():
        cells = [f"{rob[spec][o]['coef']:.3f} (p {fmt_p(rob[spec][o]['p_value'])})" for o in main]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    lines += ["", "### What this does and does not show", ""]
    if pretrend_fail:
        lines.append(
            f"- **The parallel-trends assumption is rejected** for {len(pretrend_fail)} of {len(main)} "
            "outcomes (joint test of event-study leads, p < 0.05). CBD and control zones were already "
            "diverging before 2025-01-05, so the DiD estimates above should not be read as causal "
            "effects of congestion pricing.")
    if placebo_sig:
        lines.append(
            f"- **The placebo test fails** for {' and '.join(LABELS[o].split(' (')[0].split(',')[0].lower() for o in placebo_sig)}: a fake "
            "cutoff on 2024-07-01 produces statistically significant \"effects\", which is further "
            "evidence of differential trends unrelated to the policy.")
    lines.append(
        f"- Border zones (just north of 60th St, not charged) show a trip-volume estimate of "
        f"{spill['coef']:.3f} against the same control group, similar to the CBD estimate. The "
        "contrast looks more like Manhattan vs. the outer boroughs than a CBD-specific change.")
    lines += [
        "- Descriptively (not pre-registered, pooled over trips rather than zones), average daily "
        "clean pickups changed by "
        f"{desc['cbd']['trips_per_day_pct_change']:+.1f}% in CBD zones, "
        f"{desc['border']['trips_per_day_pct_change']:+.1f}% in border zones, and "
        f"{desc['other']['trips_per_day_pct_change']:+.1f}% in all other zones (post vs pre). The "
        "pre-registered model weights every zone equally on a log scale, so proportional growth in "
        "low-volume outer-borough zones dominates its trip-volume estimate.",
        "",
        "Figures: [trends](analysis/figures/trends_cbd_vs_control.png), "
        "[event study](analysis/figures/event_study.png). Full table: "
        "[`results/did_results.csv`](results/did_results.csv).",
        END,
    ]
    return "\n".join(lines)


KEY_START, KEY_END = "<!-- KEYNUMBERS:START -->", "<!-- KEYNUMBERS:END -->"


def render_key_numbers(m: dict) -> str:
    w, a, d = m["data_window"], m["agent_eval"], m["databricks"]
    main = m["did_main"]
    fails = sum(r["pretrend_wald_p"] < ALPHA for r in main.values())
    rows = [
        ("Trips ingested (yellow + green)",
         f"{m['raw_rows_trips_total']:,} from {m['raw_files_yellow'] + m['raw_files_green']} monthly files, "
         f"{w['start']} to {w['end_exclusive']} (exclusive)"),
        ("Clean trips after quality rules", f"{m['dq_rows_retained']:,} ({m['dq_pct_retained']}% retained)"),
        ("dbt tests (DuckDB)", f"{m['dbt_tests_total']} tests: {m['dbt_tests_pass']} pass, "
                               f"{m['dbt_tests_warn']} warn (by design), {m['dbt_tests_fail']} fail"),
        ("Treatment / border zones", f"{m['cbd_zone_count']} CBD zones (MTA list), "
                                     f"{m['border_zone_count']} border zones (derived from zone polygons)"),
        ("Pre-registered DiD", f"parallel trends rejected for {fails} of {len(main)} outcomes; "
                               "estimates reported as descriptive contrasts (see Results)"),
        ("Databricks (Free Edition)",
         f"dbt build {d['dbt_pass']} pass / {d['dbt_warn']} warn / {d['dbt_error']} error on a 1/{d['sample_mod']} "
         f"sample ({d['raw_trip_rows']:,} trips); clean set identical to DuckDB: {d['fct_trips_match_duckdb']}"),
        ("Text-to-SQL agent", f"{a['execution_accuracy_pct']}% execution accuracy on {a['n_questions']} gold "
                              f"questions ({a['model']}); easy {a['by_difficulty_pct']['easy']}%, "
                              f"medium {a['by_difficulty_pct']['medium']}%, hard {a['by_difficulty_pct']['hard']}%"),
    ]
    return "\n".join([KEY_START,
                      "_Generated by `analysis/render_readme.py` from `results/metrics.json`._", "",
                      "| | |", "|---|---|", *[f"| {k} | {v} |" for k, v in rows], KEY_END])


def replace_block(text: str, start: str, end: str, block: str) -> str:
    if start not in text or end not in text:
        raise SystemExit(f"README.md is missing the {start} ... {end} markers")
    head, rest = text.split(start, 1)
    return head + block + rest.split(end, 1)[1]


def main() -> None:
    m = json.loads(METRICS.read_text())
    text = replace_block(README.read_text(), START, END, render(m))
    if KEY_START in text:
        text = replace_block(text, KEY_START, KEY_END, render_key_numbers(m))
    README.write_text(text)
    print("README generated blocks updated.")


if __name__ == "__main__":
    main()
