"""Execution-accuracy evaluation of the text-to-SQL agent on agent/eval/gold_questions.yaml.

A question is correct when the agent's result set equals the gold result set:
  - same number of rows and columns (column names ignored, column order within a row ignored);
  - row order ignored unless the question has `ordered: true`;
  - integers, strings and dates must match exactly; floats match within max(0.01, 1e-4 * |gold|).
Per-question results are cached in results/agent_eval_runs.jsonl (so a rate-limited run can
resume without re-spending quota); --fresh clears the cache for the current model.

Usage:
    python -m agent.eval.run_eval [--fresh] [--only e01,m03] [--sleep 2]
"""
import argparse
import datetime as dt
import decimal
import json
import time
from collections import defaultdict
from pathlib import Path

import yaml

from agent.graph import run
from agent.llm import model_name
from agent.schema import ROOT, connect

GOLD = ROOT / "agent" / "eval" / "gold_questions.yaml"
CACHE = ROOT / "results" / "agent_eval_runs.jsonl"
CSV_OUT = ROOT / "results" / "agent_eval.csv"


def cell(v):
    """Normalize one value to (kind, value) for comparison."""
    if v is None:
        return ("null", None)
    if isinstance(v, bool):
        return ("bool", v)
    if isinstance(v, int):
        return ("num", v, True)
    if isinstance(v, (float, decimal.Decimal)):
        f = float(v)
        return ("num", int(f), True) if f.is_integer() and isinstance(v, decimal.Decimal) else ("num", f, False)
    if isinstance(v, dt.datetime):
        return ("str", v.isoformat(sep=" "))
    if isinstance(v, dt.date):  # a date and its ISO string compare equal
        return ("str", v.isoformat())
    return ("str", str(v).strip())


def sort_key(c):
    return (c[0], round(c[1], 2) if c[0] == "num" else str(c[1]))


def cells_equal(g, p) -> bool:
    if g[0] != p[0]:
        return False
    if g[0] != "num":
        return g[1] == p[1]
    if g[2] and p[2]:  # both integral
        return g[1] == p[1]
    return abs(g[1] - p[1]) <= max(0.01, 1e-4 * abs(g[1]))


def results_match(gold_rows, pred_rows, ordered: bool) -> bool:
    if len(gold_rows) != len(pred_rows):
        return False
    g = [sorted((cell(v) for v in r), key=sort_key) for r in gold_rows]
    p = [sorted((cell(v) for v in r), key=sort_key) for r in pred_rows]
    if any(len(a) != len(b) for a, b in zip(g, p)):
        return False
    if not ordered:
        g, p = sorted(g, key=lambda r: [sort_key(c) for c in r]), sorted(p, key=lambda r: [sort_key(c) for c in r])
    return all(cells_equal(a, b) for ra, rb in zip(g, p) for a, b in zip(ra, rb))


def load_cache(model: str) -> dict:
    if not CACHE.exists():
        return {}
    out = {}
    for line in CACHE.read_text().splitlines():
        r = json.loads(line)
        if r["model"] == model:
            out[r["id"]] = r
    return out


def write_review_sheet() -> None:
    spec = yaml.safe_load(GOLD.read_text())
    con = connect()
    out = ["# Gold questions: review sheet", "",
           "_Generated by `python -m agent.eval.run_eval --review-sheet` from `gold_questions.yaml` and the "
           "current DuckDB warehouse._", ""]
    for q in spec["questions"]:
        rows = con.execute(q["sql"]).fetchall()
        shown = "; ".join(str(tuple(r)) for r in rows[:6]) + (f"; ... ({len(rows)} rows)" if len(rows) > 6 else "")
        out += [f"### {q['id']} ({q['difficulty']}{', ordered' if q.get('ordered') else ''})",
                q["question"].strip(), "", "```sql", " ".join(q["sql"].split()), "```",
                f"Gold result: {shown}", ""]
    (GOLD.parent / "gold_review.md").write_text("\n".join(out))
    print("Wrote agent/eval/gold_review.md")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--fresh", action="store_true", help="ignore cached runs for this model")
    p.add_argument("--only", default=None, help="comma-separated question ids")
    p.add_argument("--sleep", type=float, default=2.0, help="seconds between questions (rate limits)")
    p.add_argument("--allow-draft", action="store_true", help="score an unreviewed question set (debug only)")
    p.add_argument("--review-sheet", action="store_true",
                   help="write agent/eval/gold_review.md (questions + gold SQL + gold results) and exit")
    args = p.parse_args()
    if args.review_sheet:
        write_review_sheet()
        return

    spec = yaml.safe_load(GOLD.read_text())
    if not spec.get("reviewed") and not args.allow_draft:
        raise SystemExit("gold_questions.yaml is not marked reviewed: true; review it before scoring")
    questions = spec["questions"]
    if args.only:
        keep = set(args.only.split(","))
        questions = [q for q in questions if q["id"] in keep]

    model = model_name()
    cache = {} if args.fresh else load_cache(model)
    if args.fresh and CACHE.exists():
        CACHE.write_text("".join(ln + "\n" for ln in CACHE.read_text().splitlines()
                                 if json.loads(ln)["model"] != model))
    con = connect()
    for q in questions:
        if q["id"] in cache:
            continue
        gold_rows = con.execute(q["sql"]).fetchall()
        t0 = time.time()
        try:
            s = run(q["question"], with_answer=False)
            err = s.get("error") or ""
            pred_rows = s.get("rows") if not err else None
            sql = s.get("safe_sql") or s.get("sql") or ""
            attempts = s.get("attempts", 0)
        except Exception as e:  # noqa: BLE001 - API failures are recorded, not fatal
            err, pred_rows, sql, attempts = f"{type(e).__name__}: {str(e)[:300]}", None, "", 0
        correct = pred_rows is not None and results_match(gold_rows, pred_rows, q.get("ordered", False))
        rec = {"model": model, "id": q["id"], "difficulty": q["difficulty"], "correct": correct,
               "executed": pred_rows is not None, "attempts": attempts, "error": err, "sql": sql,
               "seconds": round(time.time() - t0, 1), "run_at": dt.datetime.now().isoformat(timespec="seconds")}
        with open(CACHE, "a") as f:
            f.write(json.dumps(rec) + "\n")
        cache[q["id"]] = rec
        print(f"{q['id']} {'PASS' if correct else 'FAIL'} attempts={attempts} {err[:80]}")
        time.sleep(args.sleep)

    recs = [cache[q["id"]] for q in spec["questions"] if q["id"] in cache]
    by = defaultdict(list)
    for r in recs:
        by[r["difficulty"]].append(r["correct"])
    acc = lambda xs: round(100 * sum(xs) / len(xs), 1) if xs else None  # noqa: E731
    summary = {
        "model": model, "n_questions": len(recs),
        "execution_accuracy_pct": acc([r["correct"] for r in recs]),
        "by_difficulty_pct": {d: acc(by[d]) for d in ["easy", "medium", "hard"]},
        "by_difficulty_n": {d: len(by[d]) for d in ["easy", "medium", "hard"]},
        "executed_without_error_pct": acc([r["executed"] for r in recs]),
        "needed_repair_pct": acc([r["attempts"] > 1 for r in recs]),
        "evaluated_at": max(r["run_at"] for r in recs) if recs else None,
    }
    import csv
    with open(CSV_OUT, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "difficulty", "correct", "executed", "attempts", "error", "sql"])
        w.writeheader()
        w.writerows({k: r[k] for k in w.fieldnames} for r in recs)
    if len(recs) == len(spec["questions"]):
        import sys
        sys.path.insert(0, str(ROOT / "ingestion"))
        from utils import update_metrics
        update_metrics({"agent_eval": summary})
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
