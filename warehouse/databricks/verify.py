"""Check the Databricks build against the local DuckDB build and record evidence.

Compares, for the same deterministic sample of trips:
  - dim_zone: CBD and border flags (border derived independently by each engine's spatial SQL)
    and centroid coordinates;
  - fct_trips: row count, sum of trip_id (a checksum of the clean set) and total fare.
Writes docs/databricks/verification.md and databricks_* keys in results/metrics.json.

Usage:
    python warehouse/databricks/verify.py
"""
import json
import re
import sys

import duckdb

from conn import ROOT, connect

sys.path.insert(0, str(ROOT / "ingestion"))
from utils import DB_PATH, update_metrics  # noqa: E402

CATALOG = "workspace"


def main() -> None:
    manifest = json.loads((ROOT / "data" / "warehouse_stage_databricks" / "manifest.json").read_text())
    mod = manifest["sample_mod"]
    cur = connect().cursor()
    duck = duckdb.connect(str(DB_PATH), read_only=True)

    def dbx(sql):
        cur.execute(sql)
        return cur.fetchall()

    # dim_zone
    zq = "select location_id, is_cbd, is_border_zone, centroid_lon, centroid_lat from {} order by 1"
    dz_dbx = {r[0]: tuple(r[1:]) for r in dbx(zq.format(f"{CATALOG}.marts.dim_zone"))}
    dz_duck = {r[0]: tuple(r[1:]) for r in duck.execute(zq.format("marts.dim_zone")).fetchall()}
    flags_equal = {k: v[:2] for k, v in dz_dbx.items()} == {k: v[:2] for k, v in dz_duck.items()}
    centroid_diff = max(
        (abs(dz_dbx[k][i] - dz_duck[k][i]) for k in dz_duck if dz_duck[k][2] is not None for i in (2, 3)),
        default=None)
    border_zones = sorted(k for k, v in dz_dbx.items() if v[1])

    # fct_trips on the sampled trips (file_row_number % mod = 0 <=> trip_id % mod = 0)
    fq = "select count(*), sum(cast(trip_id as decimal(38, 0))), round(sum(fare_amount), 2) from {}"
    f_dbx = tuple(dbx(fq.format(f"{CATALOG}.marts.fct_trips"))[0])
    f_duck = tuple(duck.execute(fq.format(f"marts.fct_trips where trip_id % {mod} = 0")).fetchone())
    fct_equal = tuple(int(x) if i < 2 else float(x) for i, x in enumerate(f_dbx)) == \
        tuple(int(x) if i < 2 else float(x) for i, x in enumerate(f_duck))

    log = (ROOT / "docs" / "databricks" / "dbt_build.log").read_text()
    done = re.search(r"Done\. PASS=(\d+) WARN=(\d+) ERROR=(\d+) SKIP=(\d+)", log)
    loads = json.loads((ROOT / "docs" / "databricks" / "load_counts.json").read_text())["tables"]

    md = [
        "# Databricks deployment evidence",
        "",
        "_Generated by `warehouse/databricks/verify.py`. Workspace: Databricks Free Edition, "
        "serverless SQL warehouse, Unity Catalog `workspace`._",
        "",
        f"## dbt build (`--target databricks`)\n\n`{done.group(0) if done else 'no summary found'}` "
        "(full log: [`dbt_build.log`](dbt_build.log)).",
        "",
        f"## Loaded tables\n\nRaw trips are a deterministic 1/{mod} sample (rows with "
        f"`file_row_number % {mod} = 0` in every monthly file); `zoneshift_full.*` are the full-data "
        "marts built locally from every trip.",
        "",
        "| Table | Rows |", "|---|---:|",
        *[f"| `{CATALOG}.{t}` | {n:,} |" for t, n in loads.items()],
        "",
        "## Same results as DuckDB",
        "",
        f"- `dim_zone` CBD and border flags identical: **{flags_equal}** (border zones computed by "
        f"Databricks spatial SQL: {border_zones}).",
        f"- Max centroid difference vs DuckDB (degrees): {centroid_diff:.2e}.",
        f"- `fct_trips` on the sampled trips, (rows, sum of trip_id, total fare): Databricks "
        f"{f_dbx} vs DuckDB {f_duck}; identical: **{fct_equal}**.",
    ]
    out = ROOT / "docs" / "databricks" / "verification.md"
    out.write_text("\n".join(md) + "\n")
    update_metrics({"databricks": {
        "dbt_pass": int(done.group(1)), "dbt_warn": int(done.group(2)), "dbt_error": int(done.group(3)),
        "sample_mod": mod, "raw_trip_rows": loads["raw.yellow_tripdata"] + loads["raw.green_tripdata"],
        "fct_trips_rows": int(f_dbx[0]), "dim_zone_flags_match_duckdb": flags_equal,
        "fct_trips_match_duckdb": fct_equal, "max_centroid_diff_deg": centroid_diff,
    }})
    print("\n".join(md[-4:]))


if __name__ == "__main__":
    main()
